#!/usr/bin/env node
/*
 * Extracts the external hosts the compiled theme CSS loads from, so the content security policy
 * does not have to repeat them by hand. Run after updating the theme packages.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { argv } from 'node:process';
import { fileURLToPath } from 'node:url';

const THEME_PATH = 'public/static/themes';
const OUTPUT = 'src/constants/theme-hosts.ts';

/* Theme settings that switch on an integration, see src/constants/integrations.ts. */
const INTEGRATION_SETTINGS = ['googleAnalyticsId', 'monsidoToken'];

/* statSync rather than Dirent.isDirectory, so a theme linked in rather than copied still counts. */
function themeDirectories(themePath) {
  return readdirSync(themePath).filter((name) => statSync(join(themePath, name)).isDirectory());
}

export function themeCssHosts(themePath = THEME_PATH) {
  if (!existsSync(themePath)) return [];

  const hosts = new Set();
  const pattern = /(?:url\(\s*['"]?|@import\s+(?:url\()?['"])(https:\/\/[^'")\s]+)/g;

  for (const theme of themeDirectories(themePath)) {
    for (const file of readdirSync(join(themePath, theme))) {
      if (!file.endsWith('.css')) continue;

      const css = readFileSync(join(themePath, theme, file), 'utf8');

      for (const [, url] of css.matchAll(pattern)) {
        hosts.add(new URL(url).origin);
      }
    }
  }

  return [...hosts].sort();
}

export function enabledIntegrations(themePath = THEME_PATH) {
  if (!existsSync(themePath)) return [];

  const enabled = new Set();

  for (const theme of themeDirectories(themePath)) {
    let settings;

    try {
      settings = JSON.parse(readFileSync(join(themePath, theme, 'theme.json'), 'utf8')).settings;
    } catch {
      continue;
    }

    for (const key of INTEGRATION_SETTINGS) {
      if (settings?.[key]) enabled.add(key);
    }
  }

  return [...enabled].sort();
}

/* Only when run directly: importing this module must not have side effects. */
if (argv[1] && fileURLToPath(import.meta.url) === argv[1]) {
  const hosts = themeCssHosts();
  const integrations = enabledIntegrations();

  if (!hosts.length) {
    console.error(`No hosts found under ${THEME_PATH}. Are the theme packages installed?`);
    process.exit(1);
  }

  writeFileSync(
    OUTPUT,
    `/* Generated by scripts/generate-theme-hosts.mjs. Do not edit by hand. */\n` +
      `export const THEME_CSS_HOSTS = [\n` +
      hosts.map((h) => `  '${h}',\n`).join('') +
      `];\n\n` +
      `export const ENABLED_INTEGRATION_SETTINGS = [\n` +
      integrations.map((k) => `  '${k}',\n`).join('') +
      `];\n`
  );

  console.log(`Wrote ${hosts.length} hosts and ${integrations.length} integrations to ${OUTPUT}`);
}
