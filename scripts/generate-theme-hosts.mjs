#!/usr/bin/env node
/*
 * Extracts the external hosts the compiled theme CSS loads from, so the content security policy
 * does not have to repeat them by hand. Run after updating the theme packages.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const THEME_PATH = 'public/static/themes';
const OUTPUT = 'src/constants/theme-hosts.ts';

export function themeCssHosts(themePath = THEME_PATH) {
  const hosts = new Set();
  const pattern = /(?:url\(\s*['"]?|@import\s+(?:url\()?['"])(https:\/\/[^'")\s]+)/g;

  for (const theme of readdirSync(themePath, { withFileTypes: true })) {
    if (!theme.isDirectory()) continue;

    for (const file of readdirSync(join(themePath, theme.name))) {
      if (!file.endsWith('.css')) continue;

      const css = readFileSync(join(themePath, theme.name, file), 'utf8');

      for (const [, url] of css.matchAll(pattern)) {
        hosts.add(new URL(url).origin);
      }
    }
  }

  return [...hosts].sort();
}

const hosts = themeCssHosts();

if (!hosts.length) {
  console.error(`No hosts found under ${THEME_PATH}. Are the theme packages installed?`);
  process.exit(1);
}

writeFileSync(
  OUTPUT,
  `/* Generated by scripts/generate-theme-hosts.mjs. Do not edit by hand. */\n` +
    `export const THEME_CSS_HOSTS = [\n` +
    hosts.map((h) => `  '${h}',\n`).join('') +
    `];\n`
);

console.log(`Wrote ${hosts.length} hosts to ${OUTPUT}`);
