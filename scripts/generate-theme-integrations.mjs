#!/usr/bin/env node
/* Records which optional integrations the installed themes switch on. Run after updating themes. */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { argv } from 'node:process';
import { fileURLToPath } from 'node:url';

const THEME_PATH = 'public/static/themes';
const OUTPUT = 'src/constants/theme-integrations.ts';

/* Theme settings that switch on an integration, see src/constants/integrations.ts. */
const INTEGRATION_SETTINGS = ['googleAnalyticsId', 'monsidoToken'];

export function enabledIntegrations(themePath = THEME_PATH) {
  if (!existsSync(themePath)) return [];

  const enabled = new Set();

  for (const theme of readdirSync(themePath)) {
    const themeJson = join(themePath, theme, 'theme.json');

    if (!statSync(join(themePath, theme)).isDirectory() || !existsSync(themeJson)) continue;

    let settings;

    try {
      settings = JSON.parse(readFileSync(themeJson, 'utf8')).settings;
    } catch {
      continue;
    }

    for (const key of INTEGRATION_SETTINGS) {
      if (settings?.[key]) enabled.add(key);
    }
  }

  return [...enabled].sort();
}

/* Only when run directly: importing this module must not have side effects. */
if (argv[1] && fileURLToPath(import.meta.url) === argv[1]) {
  if (!existsSync(THEME_PATH)) {
    console.error(`No themes under ${THEME_PATH}. Are the theme packages installed?`);
    process.exit(1);
  }

  const integrations = enabledIntegrations();

  writeFileSync(
    OUTPUT,
    `/* Generated by scripts/generate-theme-integrations.mjs. Do not edit by hand. */\n` +
      `export const ENABLED_INTEGRATION_SETTINGS = [\n` +
      integrations.map((key) => `  '${key}',\n`).join('') +
      `];\n`
  );

  console.log(`Wrote ${integrations.length} integrations to ${OUTPUT}`);
}
