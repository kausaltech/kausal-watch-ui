'use client';

import { useEffect } from 'react';

import { usePathname, useSearchParams } from 'next/navigation';
import Script from 'next/script';

import { stripSlashes } from '@/utils/urls';

type Props = {
  // Formatted as '<matomoUrl>?<matomoSiteId>', e.g. 'https://matomo.example.com?1' or, for
  // instances that only expose Matomo's js/ directory, 'https://webanalytics.digiaiiris.com/js?1318'
  matomoAnalyticsUrl?: string;
};

// Matomo analytics events
declare global {
  interface Window {
    _paq?: { push: (...args: unknown[]) => unknown };
  }
}

type MatomoConfig = {
  scriptUrl: string;
  trackerUrl: string;
  siteId: string;
};

/**
 * Generated by Matomo, initial trackPageView removed to be handled by the component useEffect
 */
const getTrackingScript = ({ scriptUrl, trackerUrl, siteId }: MatomoConfig) => `
  var _paq = window._paq = window._paq || [];
  /* tracker methods like "setCustomDimension" should be called before "trackPageView" */
  _paq.push(['disableCookies']);
  _paq.push(['enableLinkTracking']);
  (function() {
    _paq.push(['setTrackerUrl', ${JSON.stringify(trackerUrl)}]);
    _paq.push(['setSiteId', ${JSON.stringify(siteId)}]);
    var d=document, g=d.createElement('script'), s=d.getElementsByTagName('script')[0];
    g.async=true; g.src=${JSON.stringify(scriptUrl)}; s.parentNode.insertBefore(g,s);
  })();
`;

/**
 * Some hosted Matomo instances (e.g. Digia Iiris) expose only Matomo's `js/` directory, where the
 * tracker is `piwik.min.js` and hits go to `tracker.php`. A base URL ending in `/js` selects those
 * entry points; any other base URL uses the standard `matomo.js` and `matomo.php` at its root.
 */
export function getMatomoConfig(matomoAnalyticsUrl?: string): MatomoConfig | null {
  if (!matomoAnalyticsUrl) {
    return null;
  }

  const [matomoUrl, siteId] = matomoAnalyticsUrl.split('?');

  if (!matomoUrl || !siteId) {
    return null;
  }

  const base = stripSlashes(matomoUrl, { trailing: true });

  if (base.endsWith('/js')) {
    return { scriptUrl: `${base}/piwik.min.js`, trackerUrl: `${base}/tracker.php`, siteId };
  }

  return { scriptUrl: `${base}/matomo.js`, trackerUrl: `${base}/matomo.php`, siteId };
}

export function trackSearch(query: string, isSearchingOtherPlans: boolean, results: number) {
  if (!window._paq) {
    return;
  }

  // https://developer.matomo.org/guides/tracking-javascript-guide#internal-search-tracking
  window._paq.push([
    'trackSiteSearch',
    // Search keyword searched for
    query,
    // Search category selected in your search engine. If you do not need this, set to false
    isSearchingOtherPlans ? 'Other plans' : false,
    // Number of results in the Search results page. Zero indicates a 'No Result Search Keyword'. Set to false if you don't know
    results,
  ]);
}

export function MatomoAnalytics({ matomoAnalyticsUrl }: Props) {
  const pathname = usePathname();
  const searchParams = useSearchParams().toString();

  const config = getMatomoConfig(matomoAnalyticsUrl);
  const url = `${pathname}${searchParams ? `?${searchParams}` : ''}`;

  useEffect(() => {
    if (!window._paq) {
      return;
    }

    window._paq.push(['setCustomUrl', url]);
    window._paq.push(['setDocumentTitle', document.title]);
    window._paq.push(['trackPageView']);
  }, [url]);

  if (!config) {
    return null;
  }

  return <Script id="matomo-analytics">{getTrackingScript(config)}</Script>;
}
